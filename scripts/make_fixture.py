#!/usr/bin/env python
"""Generate a schema-correct feature stream fixture (Track A: synthetic, offline).

    python scripts/make_fixture.py                      # 2 days from the test window
    python scripts/make_fixture.py --start 2026-10-05 --days 3
    python scripts/make_fixture.py --out-dir tests/fixtures

Writes `<out-dir>/feature_stream.synthetic.jsonl` (one line per settlement period,
exactly the shape `src.serve` consumes) plus `manifest.json` (sha256 + provenance).

This is NOT data from the real topic. When the platform repo publishes
`features.gb-price.v1`, capture the real thing instead and keep this as the
offline fallback:

    python -m src.serve --kafka --capture 96 --capture-out tests/fixtures/feature_stream.captured.jsonl

Never print the file itself — use `python scripts/peek.py <file>`.
"""
from __future__ import annotations

import argparse
from datetime import date, datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.contracts import FEATURE_SET_VERSION, validate_feature_record  # noqa: E402
from src.features import day_ahead_features  # noqa: E402
from src.model import FEATURE_COLS  # noqa: E402
from src.records import make_feature_record  # noqa: E402

DEFAULT_OUT = Path(__file__).resolve().parent.parent / "tests" / "fixtures"
NAME = "feature_stream.synthetic.jsonl"


def build(start: date, days: int, model_id: str = "gb-price") -> tuple[list[str], dict]:
    lines: list[str] = []
    skipped: list[str] = []
    for n in range(days):
        day = start + timedelta(days=n)
        features = day_ahead_features(day)
        for _, row in features.iterrows():
            record = make_feature_record(row, model_id=model_id)
            errors = validate_feature_record(record, required_features=FEATURE_COLS)
            if errors:
                skipped.append(f"{record.delivery_start}: {'; '.join(errors[:2])}")
                continue
            body = record.__dict__
            payload = {
                "model_id": body["model_id"],
                "feature_set_version": body["feature_set_version"],
                "prediction_key": body["prediction_key"],
                "delivery_start": body["delivery_start"],
                "as_of": body["as_of"],
                "features": {c: body["features"][c] for c in FEATURE_COLS},
            }
            lines.append(json.dumps(payload, separators=(",", ":"), sort_keys=False))
    return lines, {
        "skipped": len(skipped),
        "skipped_examples": skipped[:3],
        "start": start.isoformat(),
        "days": days,
        "model_id": model_id,
    }


def write(lines: list[str], meta: dict, out_dir: Path) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / NAME
    text = "\n".join(lines) + "\n"
    path.write_text(text, encoding="utf-8")

    manifest = {
        "fixture": NAME,
        "source": "synthetic",
        "provenance": (
            "generated by scripts/make_fixture.py from src.features.day_ahead_features "
            "over src.data's synthetic price/forecast tables (same code path as training). "
            "Placeholder until the platform repo publishes features.gb-price.v1."
        ),
        "generated_at": datetime.now(tz=timezone.utc).isoformat().replace("+00:00", "Z"),
        "model_id": meta["model_id"],
        "feature_set_version": FEATURE_SET_VERSION,
        "feature_cols": FEATURE_COLS,
        "delivery_days": [meta["start"], f"+{meta['days']}d"],
        "entries": len(lines),
        "skipped_invalid": meta["skipped"],
        "skipped_examples": meta["skipped_examples"],
        "bytes": len(text.encode("utf-8")),
        "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "how_to_consume": f"python -m src.serve --replay {NAME}",
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python scripts/make_fixture.py",
                                description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--start", default="2026-10-05", help="first delivery day (test window)")
    p.add_argument("--days", type=int, default=2, help="number of delivery days")
    p.add_argument("--model-id", default="gb-price")
    p.add_argument("--out-dir", default=str(DEFAULT_OUT))
    args = p.parse_args(argv)

    lines, meta = build(date.fromisoformat(args.start), args.days, args.model_id)
    if not lines:
        print("no valid records produced — is the synthetic price history loaded?", file=sys.stderr)
        return 1
    manifest = write(lines, meta, Path(args.out_dir))

    if manifest["skipped_invalid"]:
        print(f"warning: skipped {manifest['skipped_invalid']} rows that failed validation "
              f"(e.g. {manifest['skipped_examples'][0] if manifest['skipped_examples'] else '?'})",
              file=sys.stderr)
    print(json.dumps({k: manifest[k] for k in
                      ("fixture", "entries", "bytes", "sha256", "feature_set_version")}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
